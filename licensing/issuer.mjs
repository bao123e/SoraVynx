/* Owner-side signing only. Never ship the private key with the customer tool. */
import {generateKeyPairSync,createPrivateKey,createPublicKey,sign,verify,randomBytes} from 'node:crypto';
import {readFileSync,writeFileSync,existsSync,mkdirSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createInterface} from 'node:readline/promises';
export const plans=Object.freeze({week:7,month:30,year:365,lifetime:0});
export function issueLicense(privatePem,machine,plan,now=Math.floor(Date.now()/1000)) {
 if(!/^[a-f0-9]{64}$/.test(machine))throw new Error('Machine code must contain exactly 64 lowercase hexadecimal characters.');
 if(!Object.hasOwn(plans,plan))throw new Error('Plan must be week, month, year or lifetime.');
 if(!Number.isSafeInteger(now)||now<1000000000||now>9999999999)throw new Error('Invalid issuing time.');
 const expires=plans[plan]?now+plans[plan]*86400:0;
 if(expires>9999999999)throw new Error('Expiry exceeds protocol limit.');
 const body=`SV1.${now}.${String(expires).padStart(10,'0')}.${machine}.${randomBytes(16).toString('hex')}`;
 const signature=sign('sha256',Buffer.from(body),{key:createPrivateKey(privatePem),dsaEncoding:'ieee-p1363'});
 return body+'.'+signature.toString('hex');
}
export function verifyLicense(publicPem,key,machine,now=Math.floor(Date.now()/1000)) {
 if(!/^SV1\.\d{10}\.\d{10}\.[a-f0-9]{64}\.[a-f0-9]{32}\.[a-f0-9]{128}$/.test(key))return false;
 const a=key.split('.'),issued=Number(a[1]),expires=Number(a[2]);
 if(a[3]!==machine||issued>now+300||(expires&&expires<=issued)||(expires&&now>=expires))return false;
 return verify('sha256',Buffer.from(a.slice(0,5).join('.')),{key:publicPem,dsaEncoding:'ieee-p1363'},Buffer.from(a[5],'hex'));
}
export function publicHeader(publicPem) {
 const jwk=createPublicKey(publicPem).export({format:'jwk'});
 if(jwk.crv!=='P-256')throw new Error('Expected P-256 issuer key.');
 const xy=Buffer.concat([Buffer.from(jwk.x,'base64url'),Buffer.from(jwk.y,'base64url')]);
 return '/* Public key generated by SoraVynx owner setup. No private key here. */\n#ifndef SORAVYNX_LICENSE_PUBLIC_KEY_H\n#define SORAVYNX_LICENSE_PUBLIC_KEY_H\n#define SV_LICENSE_CONFIGURED 1\nstatic const unsigned char sv_license_public_xy[64]={'+[...xy].map(b=>'0x'+b.toString(16).padStart(2,'0')).join(',')+'};\n#endif\n';
}
function option(name,fallback){const i=process.argv.indexOf('--'+name);if(i<0)return fallback;const v=process.argv[i+1];if(!v||v.startsWith('--'))throw new Error('Missing --'+name+' value.');return v;}
async function cli(){
 const command=process.argv[2];
 if(command==='init'){
  const directory=resolve(option('out','licensing/secrets')),header=resolve(option('header','source/license_public_key.h'));
  const privatePath=resolve(directory,'issuer-private.pem'),publicPath=resolve(directory,'issuer-public.pem');
  if(existsSync(privatePath)||existsSync(publicPath))throw new Error('Issuer already exists. Back it up; do not replace it or lose existing customer key compatibility.');
  mkdirSync(directory,{recursive:true,mode:0o700});mkdirSync(dirname(header),{recursive:true});
  const {privateKey,publicKey}=generateKeyPairSync('ec',{namedCurve:'prime256v1'});
  const priv=privateKey.export({type:'pkcs8',format:'pem'}),pub=publicKey.export({type:'spki',format:'pem'});
  writeFileSync(privatePath,priv,{mode:0o600,flag:'wx'});writeFileSync(publicPath,pub,{mode:0o600,flag:'wx'});writeFileSync(header,publicHeader(pub));
  console.log('Issuer created. Keep issuer-private.pem private and backed up.\nRebuild BOTH launcher and runtime after uploading only the PUBLIC source/license_public_key.h.');
 }else if(command==='wizard'){
  const io=createInterface({input:process.stdin,output:process.stdout});
  try {
   const machine=(await io.question('Paste customer machine code: ')).trim().toLowerCase();
   const choice=(await io.question('Plan (7 / 30 / 365 / lifetime): ')).trim();
   const plan=({'7':'week','30':'month','365':'year','lifetime':'lifetime'})[choice];
   const pem=readFileSync(option('private','licensing/secrets/issuer-private.pem'),'utf8');
   console.log('\nCopy the complete key below and send privately to the customer:\n'+issueLicense(pem,machine,plan));
  }finally{io.close();}
 }else if(command==='issue'){
  const file=option('private','licensing/secrets/issuer-private.pem'),machine=option('machine',''),plan=option('plan','');
  console.log(issueLicense(readFileSync(file,'utf8'),machine,plan));
 }else throw new Error('Usage: node licensing/issuer.mjs init [--out DIR] [--header FILE]\n       node licensing/issuer.mjs issue --machine MACHINE_CODE --plan week|month|year|lifetime [--private FILE]');
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){try{await cli();}catch(e){console.error(e.message);process.exitCode=1;}}
